// Trink Fit data structure starter

enum ExerciseCategory { cardio, abs, legs, arms, fullBody, hiit, stretch }

enum LevelType { beginner, intermediate, advanced }

enum EquipmentType { none, dumbbell, resistanceBand, gym }

class ExerciseItem {
  final String id;
  final String name;
  final ExerciseCategory category;
  final LevelType level;
  final int durationSec;
  final int calories;
  final EquipmentType equipment;
  final String imageAsset;
  final String gifAsset;
  final String description;

  const ExerciseItem({
    required this.id,
    required this.name,
    required this.category,
    required this.level,
    required this.durationSec,
    required this.calories,
    required this.equipment,
    required this.imageAsset,
    required this.gifAsset,
    required this.description,
  });
}

class ProgramDay {
  final int day;
  final List<String> exerciseIds;

  const ProgramDay({
    required this.day,
    required this.exerciseIds,
  });
}

class ProgramItem {
  final String id;
  final String title;
  final String group;
  final LevelType level;
  final int totalDays;
  final EquipmentType equipment;
  final bool isPremium;
  final List<ProgramDay> days;

  const ProgramItem({
    required this.id,
    required this.title,
    required this.group,
    required this.level,
    required this.totalDays,
    required this.equipment,
    required this.isPremium,
    required this.days,
  });
}

